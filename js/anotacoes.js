/*
DECLARAÇÕES:

var: Declara uma variável com escopo global ou de função.
let: Declara uma variável com escopo de bloco.
const: Declara uma constante (valor não pode ser reatribuído).

TIPOS DE DADOS:

- String: Sequência de caracteres, delimitada por aspas simples ou duplas.
- Number: Números inteiros ou de ponto flutuante.
- Boolean: Verdadeiro (true) ou falso (false).
- Array: Lista ordenada de valores, delimitada por colchetes [].
- Object: Coleção de pares chave-valor, delimitada por chaves {}.
- Null: Representa a ausência intencional de qualquer valor.
- Undefined: Variável declarada, mas sem valor atribuído.

OPERADORES:

Aritméticos: 
    + (adição) 
    - (subtração) 
    * (multiplicação) 
    / (divisão) 
    % (módulo)
Comparação: 
    == (igualdade) 
    === (igualdade estrita) 
    != (desigualdade) 
    !== (desigualdade estrita) 
    > (maior que) 
    < (menor que) 
    >= (maior ou igual) 
    <= (menor ou igual)
Lógicos: 
    && (E lógico) 
    || (OU lógico) 
    ! (NÃO lógico)
Atribuição:
    = (atribuição)
    += (adição e atribuição)
    -= (subtração e atribuição)
    *= (multiplicação e atribuição)
    /= (divisão e atribuição)
Incremento/Decremento:
    ++ (incremento)
    -- (decremento) 

CONTROLE DE FLUXO:
- if, else if, else: Estruturas condicionais.
- switch: Estrutura de seleção múltipla.
- for: Laço de repetição com contador.
- while: Laço de repetição enquanto a condição for verdadeira.

FUNÇÕES:
- Tradicional: function nomeDaFuncao() { ... } 
- Arrow function: const nomeDaFuncao = () => { ... }
- Anônima: function() { ... }











*/